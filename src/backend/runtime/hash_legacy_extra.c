static void ptn_php_haval_init(PHP_HAVAL_CTX *context, int passes, short output) {
    context->count[0] = context->count[1] = 0;
    memcpy(context->state, D0, sizeof(D0));
    context->passes = (char)passes;
    context->output = output;
    context->Transform = passes == 3 ? PHP_3HAVALTransform : (passes == 4 ? PHP_4HAVALTransform : PHP_5HAVALTransform);
}

/* {{{ PHP_HAVALUpdate */
static void PHP_HAVALUpdate(PHP_HAVAL_CTX *context, const unsigned char *input, size_t inputLen)
{
	unsigned int index, partLen;
	size_t i;

	/* Compute number of bytes mod 128 */
	index = (unsigned int) ((context->count[0] >> 3) & 0x7F);
	/* Update number of bits */
	if ((context->count[0] += ((uint32_t) inputLen << 3)) < ((uint32_t) inputLen << 3)) {
		context->count[1]++;
	}
	context->count[1] += (uint32_t) (inputLen >> 29);

	partLen = 128 - index;

	/* Transform as many times as possible.
	 */
	if (inputLen >= partLen) {
		memcpy((unsigned char*) & context->buffer[index], (unsigned char*) input, partLen);
		context->Transform(context->state, context->buffer);

		for (i = partLen; i + 127 < inputLen; i += 128) {
			context->Transform(context->state, &input[i]);
		}

		index = 0;
	} else {
		i = 0;
	}

	/* Buffer remaining input */
	memcpy((unsigned char*) &context->buffer[index], (unsigned char*) &input[i], inputLen - i);
}
