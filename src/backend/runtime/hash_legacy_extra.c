static int ptn_hash_extra_haval_digest_bytes(const char *algo, const unsigned char *input, size_t input_len, unsigned char digest[32], size_t *digest_len) {
    int bits = 0;
    int passes = 0;
    if (sscanf(algo, "haval%d,%d", &bits, &passes) != 2) {
        return 0;
    }
    if (!((passes == 3 || passes == 4 || passes == 5) && (bits == 128 || bits == 160 || bits == 192 || bits == 224 || bits == 256))) {
        return 0;
    }
    PHP_HAVAL_CTX ctx;
    ptn_php_haval_init(&ctx, passes, (short)bits);
    if (input_len != 0) {
        PHP_HAVALUpdate(&ctx, input, input_len);
    }
    switch (bits) {
        case 128:
            PHP_HAVAL128Final(digest, &ctx);
            *digest_len = 16;
            return 1;
        case 160:
            PHP_HAVAL160Final(digest, &ctx);
            *digest_len = 20;
            return 1;
        case 192:
            PHP_HAVAL192Final(digest, &ctx);
            *digest_len = 24;
            return 1;
        case 224:
            PHP_HAVAL224Final(digest, &ctx);
            *digest_len = 28;
            return 1;
        case 256:
            PHP_HAVAL256Final(digest, &ctx);
            *digest_len = 32;
            return 1;
    }
    return 0;
}

