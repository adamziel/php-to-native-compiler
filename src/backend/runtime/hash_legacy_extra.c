{ \
	register uint64_t a, b, c, tmpa, x0, x1, x2, x3, x4, x5, x6, x7; \
	uint64_t aa, bb, cc; \
	unsigned int pass_no; \
	\
	a = state[0]; \
	b = state[1]; \
	c = state[2]; \
	\
	split(str); \
	\
	compress(passes); \
	\
	state[0] = a; \
	state[1] = b; \
	state[2] = c; \
}
